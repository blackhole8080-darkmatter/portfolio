/* ============================================================
   Portfolio runtime. Data comes from data.js (generated by
   scripts/sync_github.py); nothing here is hard-coded to a repo.
   ============================================================ */
(() => {
  "use strict";

  const DATA = window.PORTFOLIO || { projects: [], also: [], languages: [], stats: {}, profile: {} };
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  const ACCENTS = ["#c8ff4d", "#74a9ff", "#ff8199", "#b79cff", "#5eead4", "#ffb86b", "#8fe388", "#e0a3ff"];
  const LANG_COLORS = {
    Python: "#74a9ff",
    TypeScript: "#5ea9ff",
    JavaScript: "#c8ff4d",
    HTML: "#ff8199",
    CSS: "#b79cff",
    PLpgSQL: "#ffb86b",
    "C#": "#8fe388",
    VBScript: "#e0a3ff",
  };

  const $ = (sel, root = document) => root.querySelector(sel);
  const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));
  const esc = (s = "") =>
    String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

  /* ---------------------------------------------------------- header bits */
  const year = new Date().getFullYear();
  for (const id of ["year", "foot-year"]) {
    const el = document.getElementById(id);
    if (el) el.textContent = String(year);
  }
  if (DATA.profile?.url) {
    for (const id of ["nav-github", "hero-github", "contact-github", "also-github"]) {
      const el = document.getElementById(id);
      if (el) el.href = id === "also-github" ? DATA.profile.url + "?tab=repositories" : DATA.profile.url;
    }
    const handle = document.getElementById("github-handle");
    if (handle) handle.textContent = DATA.profile.login;
  }
  const repoCount = document.getElementById("repo-count");
  if (repoCount && DATA.stats?.projects) repoCount.textContent = String(DATA.stats.projects);

  const synced = document.getElementById("synced");
  if (synced && DATA.generated) {
    synced.textContent = new Date(DATA.generated + "T12:00:00").toLocaleDateString(undefined, {
      year: "numeric", month: "short", day: "numeric",
    });
  }

  /* ---------------------------------------------------------- stats */
  const statValues = {
    Projects: DATA.stats.projects ?? DATA.projects.length,
    Commits: DATA.stats.commits ?? 0,
    Languages: DATA.stats.languages ?? DATA.languages.length,
    "Live games": DATA.projects.filter((p) => p.live).length,
  };
  $$("#stats dd").forEach((dd) => {
    const label = dd.parentElement.querySelector("dt")?.textContent ?? "";
    if (label in statValues) dd.dataset.count = String(statValues[label]);
    dd.textContent = "0";
    if (statValues[label] >= 1000) dd.dataset.suffix = "";
  });

  /* ---------------------------------------------------------- hero rail */
  const rail = document.getElementById("rail");
  if (rail && DATA.projects.length) {
    const flagship = DATA.projects[0];
    const live = DATA.projects.find((p) => p.live);
    const stack = DATA.languages.slice(0, 5).map((l) => l.name).join(" · ");
    const when = DATA.generated
      ? new Date(DATA.generated + "T12:00:00").toLocaleDateString(undefined, { month: "short", day: "numeric" })
      : "recently";
    rail.innerHTML = `
      <div class="rail-item">
        <span class="rail-label">Flagship</span>
        <p><strong>${esc(flagship.title)}</strong> — ${esc(flagship.tagline)}</p>
      </div>
      ${live ? `<div class="rail-item">
        <span class="rail-label">Live now</span>
        <p><a href="${esc(live.live)}" target="_blank" rel="noopener">${esc(live.title)}</a> — playable in the browser.</p>
      </div>` : ""}
      <div class="rail-item">
        <span class="rail-label">Toolbox</span>
        <p>${esc(stack)}</p>
      </div>
      <div class="rail-item">
        <span class="rail-label">Data</span>
        <p>Synced ${esc(when)} from the GitHub API.</p>
      </div>`;
  }

  /* ---------------------------------------------------------- projects */
  const grid = document.getElementById("projects");
  const categories = DATA.categories || {};

  const cardHTML = (p, i) => {
    const accent = ACCENTS[i % ACCENTS.length];
    const wide = i === 0 ? " wide" : "";
    const langs = (p.languages || []).filter((l) => l.share > 0).slice(0, 3)
      .map((l) => `<span class="lang-pill"><i style="color:${LANG_COLORS[l.name] || "#8e919c"}"></i>${esc(l.name)} ${l.share}%</span>`)
      .join("");
    const stars = p.stars > 0 ? `<span class="star">★ ${p.stars}</span>` : "";
    const live = p.live
      ? `<a class="live" href="${esc(p.live)}" target="_blank" rel="noopener">Live <span aria-hidden="true">↗</span></a>`
      : "";
    return `
      <article class="card reveal${wide}" data-cats="${esc((p.categories || []).join(" "))}"
               style="--accent:${accent};--delay:${Math.min(i, 6) * 70}ms">
        <div class="card-body">
          <div>
            <div class="card-top">
              <span class="idx">${String(i + 1).padStart(2, "0")}</span>
              <span class="meta">${stars}<span>${p.year}</span></span>
            </div>
            <h3>${esc(p.title)}</h3>
            <p class="tagline">${esc(p.tagline)}</p>
          </div>
          <div>
            <p class="blurb">${esc(p.blurb)}</p>
            ${p.highlight ? `<span class="highlight">${esc(p.highlight)}</span>` : ""}
          </div>
        </div>
        <div class="card-foot">
          <div class="langs-inline">${langs}</div>
          <div class="card-links">
            ${live}
            <a href="${esc(p.url)}" target="_blank" rel="noopener">Source <span aria-hidden="true">↗</span></a>
          </div>
        </div>
      </article>`;
  };

  if (grid) grid.innerHTML = DATA.projects.map(cardHTML).join("");

  /* filter chips are rendered here; the click handler (with FLIP) lives in motion.js */
  const filterBar = document.getElementById("filters");
  if (filterBar && DATA.projects.length) {
    const used = [...new Set(DATA.projects.flatMap((p) => p.categories || []))];
    const buttons = [["all", "All work"], ...used.map((c) => [c, categories[c] || c])];
    filterBar.innerHTML = buttons
      .map(([key, label], i) =>
        `<button class="filter" data-filter="${esc(key)}" aria-pressed="${i === 0}">${esc(label)}</button>`)
      .join("");
  }

  /* ---------------------------------------------------------- languages */
  const langWrap = document.getElementById("languages");
  if (langWrap && DATA.languages.length) {
    langWrap.innerHTML = DATA.languages
      .map((l) => `
        <div class="lang-row">
          <span class="lang-name">${esc(l.name)}</span>
          <span class="lang-bar"><i data-w="${l.share}" style="background:linear-gradient(90deg,${LANG_COLORS[l.name] || "#c8ff4d"},rgba(255,255,255,.25))"></i></span>
          <span class="lang-pct">${l.share}%</span>
        </div>`)
      .join("");
  }

  /* ---------------------------------------------------------- also */
  const alsoWrap = document.getElementById("also");
  if (alsoWrap) {
    alsoWrap.innerHTML = DATA.also
      .map((p) => `
        <li><a href="${esc(p.url)}" target="_blank" rel="noopener">
          <span class="t">${esc(p.title)}</span>
          <span class="c">${esc((p.languages?.[0]?.name) || "—")}</span>
          <span aria-hidden="true">↗</span>
        </a></li>`)
      .join("");
  }

  /* ---------------------------------------------------------- reveal */
  const revealables = $$(".reveal");
  if ("IntersectionObserver" in window && !reduceMotion) {
    const io = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("in");
        io.unobserve(entry.target);
        if (entry.target.classList.contains("langs")) {
          $$(".lang-bar i", entry.target).forEach((bar, i) => {
            setTimeout(() => { bar.style.width = `${bar.dataset.w}%`; }, i * 90);
          });
        }
      });
    }, { rootMargin: "0px 0px -12% 0px", threshold: 0.15 });
    revealables.forEach((el) => io.observe(el));
  } else {
    revealables.forEach((el) => el.classList.add("in"));
    $$("dd", document.getElementById("stats") || document).forEach((dd) => { dd.textContent = dd.dataset.count || "0"; });
    $$(".lang-bar i").forEach((bar) => { bar.style.width = `${bar.dataset.w}%`; });
  }

  /* ---------------------------------------------------------- pointer light */
  const spotlight = document.getElementById("spotlight");
  if (spotlight && window.matchMedia("(pointer: fine)").matches) {
    document.body.classList.add("has-pointer");
    let raf = 0, mx = 0, my = 0;
    window.addEventListener("pointermove", (e) => {
      mx = e.clientX; my = e.clientY;
      if (raf) return;
      raf = requestAnimationFrame(() => {
        raf = 0;
        spotlight.style.setProperty("--mx", `${mx}px`);
        spotlight.style.setProperty("--my", `${my}px`);
      });
    }, { passive: true });
  }

  /* ---------------------------------------------------------- nav state */
  const nav = $(".nav");
  const onScroll = () => nav?.classList.toggle("scrolled", window.scrollY > 24);
  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });

  /* ---------------------------------------------------------- hero field */
  const canvas = document.getElementById("field");
  if (canvas && !reduceMotion) {
    const ctx = canvas.getContext("2d");
    let w = 0, h = 0, dpr = 1, dots = [];
    const pointer = { x: -9999, y: -9999 };

    const resize = () => {
      const rect = canvas.getBoundingClientRect();
      dpr = Math.min(window.devicePixelRatio || 1, 2);
      w = rect.width; h = rect.height;
      canvas.width = Math.round(w * dpr);
      canvas.height = Math.round(h * dpr);
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      const count = Math.min(90, Math.max(34, Math.round((w * h) / 24000)));
      dots = Array.from({ length: count }, () => ({
        x: Math.random() * w,
        y: Math.random() * h,
        vx: (Math.random() - 0.5) * 0.16,
        vy: (Math.random() - 0.5) * 0.16,
        r: Math.random() * 1.5 + 0.5,
      }));
    };

    const linkDist = () => Math.min(150, Math.max(95, w * 0.09));

    const draw = () => {
      ctx.clearRect(0, 0, w, h);
      const max = linkDist();

      for (const d of dots) {
        d.x += d.vx; d.y += d.vy;
        if (d.x < 0 || d.x > w) d.vx *= -1;
        if (d.y < 0 || d.y > h) d.vy *= -1;

        const dx = d.x - pointer.x, dy = d.y - pointer.y;
        const pd = Math.hypot(dx, dy);
        if (pd < 130 && pd > 0.01) {
          d.x += (dx / pd) * 0.6;
          d.y += (dy / pd) * 0.6;
        }

        ctx.beginPath();
        ctx.arc(d.x, d.y, d.r, 0, Math.PI * 2);
        ctx.fillStyle = "rgba(200,255,77,0.42)";
        ctx.fill();
      }

      for (let i = 0; i < dots.length; i++) {
        for (let j = i + 1; j < dots.length; j++) {
          const a = dots[i], b = dots[j];
          const dist = Math.hypot(a.x - b.x, a.y - b.y);
          if (dist > max) continue;
          const alpha = (1 - dist / max) * 0.13;
          ctx.strokeStyle = `rgba(190,210,255,${alpha})`;
          ctx.lineWidth = 0.7;
          ctx.beginPath();
          ctx.moveTo(a.x, a.y);
          ctx.lineTo(b.x, b.y);
          ctx.stroke();
        }
      }
      requestAnimationFrame(draw);
    };

    window.addEventListener("resize", resize);
    canvas.addEventListener("pointermove", (e) => {
      const r = canvas.getBoundingClientRect();
      pointer.x = e.clientX - r.left;
      pointer.y = e.clientY - r.top;
    });
    canvas.addEventListener("pointerleave", () => { pointer.x = -9999; pointer.y = -9999; });

    resize();
    requestAnimationFrame(draw);
  }
})();
